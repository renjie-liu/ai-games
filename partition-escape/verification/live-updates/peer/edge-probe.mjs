import assert from 'node:assert/strict';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const gameRoot=process.env.PARTITION_GAME_ROOT||process.argv[2];
if(!gameRoot)throw new Error('Set PARTITION_GAME_ROOT or pass the partition-escape directory as argv[1]');
const {Room}=await import(pathToFileURL(path.join(path.resolve(gameRoot),'world.mjs')).href);
const {PublicUpdates}=await import(pathToFileURL(path.join(path.resolve(gameRoot),'live-updates.mjs')).href);
const r=new Room({west:'human',east:'live'}),j={started:true,ended:false,epoch:1,scope:'scope',speaking:true},sent=[];
let timer;
const u=new PublicUpdates(r,j,x=>sent.push(x),{now:()=>0,schedule:f=>(timer=f,1),cancel:()=>{}});
const c={type:'action',id:'power-on'},result=r.command('west',c);
u.enqueue('west',c,result);timer();
const speakingResult={sameEpoch:j.epoch,events:result.receipt.roomEventIds,sent:sent.length,canceled:u.stats.canceled};
const r2=new Room({west:'human',east:'live'}),j2={...j,speaking:false};
const u2=new PublicUpdates(r2,j2,()=>{},{now:()=>0,schedule:()=>1,cancel:()=>{}});
for(let i=0;i<127;i++)u2.seen.add(-i-1);
r2.command('east',{type:'action',id:'send-key'});const accept={type:'accept',id:r2.pending.id};const ar=r2.command('west',accept);u2.enqueue('west',accept,ar);
assert.equal(speakingResult.sent,1);assert.equal(speakingResult.canceled,0);assert.equal(u2.seen.size,128);
process.stdout.write(JSON.stringify({speakingResult,dedupeSizeAfterTwoEventReceipt:u2.seen.size},null,2)+'\n');
